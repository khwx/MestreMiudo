export function getTranslation(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const translation = translations[locale]?.[key] || translations['pt-PT'][key] || key;
  if (!params) return translation;
  return translation.replace(/\{(\w+)\}/g, (match, key) => String(params[key] ?? match));
}